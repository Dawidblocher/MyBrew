window.useT = function useT(lang) {
  return React.useCallback((path) => {
    const parts = path.split(".");
    let v = I18N[lang] || I18N.pl;
    for (const p of parts) v = v?.[p];
    if (v == null) return path;
    return v;
  }, [lang]);
};
